    @classmethod
    def parse_from_bytes(cls, data: bytes, offset: int) -> tuple[int, Self]:
        fields = HCI_Object.fields_from_dataclass(cls)
        offset, kwargs = HCI_Object.dict_and_offset_from_bytes(data, offset, fields)
